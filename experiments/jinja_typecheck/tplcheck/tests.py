"""Typed stand-ins for Jinja's builtin tests (``x is defined`` and friends)."""

from __future__ import annotations

from collections.abc import Iterable, Mapping, Sequence
from typing import Any

from typing_extensions import TypeIs


def defined(value: object) -> bool: ...
def undefined(value: object) -> bool: ...
def none(value: object) -> TypeIs[None]: ...
def string(value: object) -> TypeIs[str]: ...
def number(value: object) -> TypeIs[int | float]: ...
def mapping(value: object) -> TypeIs[Mapping[Any, Any]]: ...
def iterable(value: object) -> TypeIs[Iterable[Any]]: ...
def sequence(value: object) -> TypeIs[Sequence[Any]]: ...
def odd(value: int) -> bool: ...
def even(value: int) -> bool: ...
def divisibleby(value: int, num: int) -> bool: ...
def eq(value: object, other: object) -> bool: ...
def ne(value: object, other: object) -> bool: ...
def lt(value: object, other: object) -> bool: ...
def gt(value: object, other: object) -> bool: ...
def in_(value: object, seq: Iterable[object]) -> bool: ...
def sameas(value: object, other: object) -> bool: ...
def true(value: object) -> bool: ...
def false(value: object) -> bool: ...
def boolean(value: object) -> bool: ...
def integer(value: object) -> TypeIs[int]: ...
def float_(value: object) -> TypeIs[float]: ...
def lower(value: str) -> bool: ...
def upper(value: str) -> bool: ...
def callable_(value: object) -> bool: ...
def escaped(value: object) -> bool: ...
def le(value: object, other: object) -> bool: ...
def ge(value: object, other: object) -> bool: ...
def filter_(value: str) -> bool: ...
def test_(value: str) -> bool: ...
