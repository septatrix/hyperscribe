"""Generate shadow modules and a typed ``get_template`` stub, then run mypy."""

from __future__ import annotations

import importlib
import os
import re
import sys
from dataclasses import dataclass, replace
from pathlib import Path

from jinja2 import TemplateSyntaxError
from mypy import api

from .shadow import (
    Config,
    TemplateInfo,
    UnsupportedError,
    make_environment,
    parse_header,
    translate,
)

SUFFIXES = {".jinja2", ".jinja", ".j2", ".html", ".tmpl"}


@dataclass
class Result:
    output: str
    status: int


def _identifier(name: str) -> str:
    return re.sub(r"\W", "_", name)


def _class_name(name: str) -> str:
    return "".join(part.capitalize() for part in _identifier(name).split("_")) or "T"


def generate(
    templates: Path,
    shadow_dir: Path,
    stub: Path | None,
    config: Config | None = None,
) -> tuple[list[Path], list[str]]:
    """Write one shadow module per annotated template (and the stub).

    Returns the shadow files and any problems found while translating.
    """
    config = config or Config()
    environment = make_environment(config)
    shadow_dir.mkdir(parents=True, exist_ok=True)
    for stale in shadow_dir.glob("*.py"):
        stale.unlink()
    # Contexts are TypedDicts defined in the project, so they have to be importable.
    # Explicit MYPYPATH entries win over whatever is already on sys.path.
    for entry in reversed(
        [os.getcwd(), *filter(None, os.environ.get("MYPYPATH", "").split(":"))]
    ):
        if entry in sys.path:
            sys.path.remove(entry)
        sys.path.insert(0, entry)
    importlib.invalidate_caches()
    annotated: dict[str, tuple[Path, str, TemplateInfo]] = {}
    for path in sorted(templates.rglob("*")):
        if path.suffix not in SUFFIXES:
            continue
        name = path.relative_to(templates).as_posix()
        source = path.read_text(encoding="utf-8")
        header = parse_header(source)
        if header is not None or config.lenient:
            context = header.context if header is not None else None
            info = TemplateInfo(_identifier(name), context)
            annotated[name] = (path, source, info)
    infos = {name: info for name, (_, _, info) in annotated.items()}
    written: list[Path] = []
    problems: list[str] = []
    registry: list[tuple[str, str]] = []
    for name, (path, source, info) in annotated.items():
        try:
            code = translate(source, str(path), environment, infos, config)
        except UnsupportedError as error:
            problems.append(f"{path}:{error.lineno}: error: {error.what} [tplcheck]")
            continue
        except TemplateSyntaxError as error:
            problems.append(
                f"{path}:{error.lineno}: error: {error.message} [tplcheck-syntax]"
            )
            continue
        except ValueError as error:
            problems.append(f"{path}:1: error: {error} [tplcheck]")
            continue
        target = shadow_dir / f"{info.module}.py"
        target.write_text(code, encoding="utf-8")
        written.append(target)
        if info.context:
            registry.append((name, info.context))
    if stub is not None:
        stub.write_text(_stub(registry), encoding="utf-8")
    return written, problems


def _stub(registry: list[tuple[str, str]]) -> str:
    lines = [
        "# Generated by tplcheck; do not edit.",
        "from typing import Literal, overload",
        "",
        "from jinja2 import Environment, Template",
        "from typing_extensions import Unpack",
    ]
    for module in sorted({ctx.rpartition(".")[0] for _, ctx in registry if "." in ctx}):
        lines.append(f"import {module}")
    lines.append("")
    for name, ctx in registry:
        lines += [
            f"class {_class_name(name)}(Template):",
            f"    def render(self, **context: Unpack[{ctx}]) -> str: ...",
            "",
        ]
    # No catch-all overload: asking for an unannotated template is an error.
    signature = "def get_template(env: Environment, name: {}) -> {}: ..."
    if len(registry) == 1:
        name, _ = registry[0]
        lines.append(signature.format(f"Literal[{name!r}]", _class_name(name)))
    elif registry:
        for name, _ in registry:
            lines += [
                "@overload",
                signature.format(f"Literal[{name!r}]", _class_name(name)),
            ]
    lines.append("")
    return "\n".join(lines)


def remap(output: str, files: list[Path]) -> str:
    """Point mypy errors in shadow modules back at the template line."""
    markers: dict[str, list[str]] = {}
    sources: dict[str, str] = {}
    for file in files:
        text = file.read_text(encoding="utf-8").splitlines()
        markers[str(file)] = text
        sources[str(file)] = text[0].removeprefix("# tplcheck: ")
    pattern = re.compile(r"^(?P<file>.+?\.py):(?P<line>\d+)(?P<rest>:.*)$")
    result = []
    for line in output.splitlines():
        match = pattern.match(line)
        if match and match["file"] in markers:
            code = markers[match["file"]][int(match["line"]) - 1]
            tpl = re.search(r"# tpl:(\d+)$", code)
            if tpl:
                line = f"{sources[match['file']]}:{tpl[1]}{match['rest']}"
        result.append(line)
    return "\n".join(result)


def check(
    templates: Path,
    shadow_dir: Path,
    stub: Path | None,
    mypy_args: list[str],
    config: Config | None = None,
) -> Result:
    config = config or Config()
    files, problems = generate(templates, shadow_dir, stub, config)
    output = "\n".join(problems)
    status = 1 if problems else 0
    if files:
        stdout, stderr, code = api.run([*mypy_args, *map(str, files)])
        output += ("\n" if output else "") + remap(stdout + stderr, files)
        status = status or code
    return Result(output.strip(), status)


def coverage(templates: Path, config: Config) -> Result:
    """Translate every template (annotated or not) and report what fails.

    Meant for sizing up an existing project before annotating it:
    contexts are untyped, but every construct has to be understood
    and the generated Python has to be valid.
    """
    config = replace(config, lenient=True)
    environment = make_environment(config)
    sources = {
        path.relative_to(templates).as_posix(): path
        for path in sorted(templates.rglob("*"))
        if path.suffix in SUFFIXES
    }
    infos = {name: TemplateInfo(_identifier(name), None) for name in sources}
    failures: dict[str, list[str]] = {}
    translated = 0
    for name, path in sources.items():
        source = path.read_text(encoding="utf-8")
        try:
            code = translate(source, name, environment, infos, config)
            compile(code, name, "exec")
            translated += 1
        except UnsupportedError as error:
            failures.setdefault(error.what, []).append(f"{name}:{error.lineno}")
        except Exception as error:  # report, don't stop
            reason = f"{type(error).__name__}: {error}"
            failures.setdefault(reason, []).append(name)
    lines = [f"{translated} of {len(sources)} templates translated"]
    for reason, where in sorted(failures.items(), key=lambda item: -len(item[1])):
        lines.append(f"  {len(where):4}  {reason}  (e.g. {where[0]})")
    return Result("\n".join(lines), 0 if translated == len(sources) else 1)
