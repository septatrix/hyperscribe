"""Typed stand-ins for Jinja's builtin filters (a representative subset)."""

from __future__ import annotations

from collections.abc import Iterable, Iterator, Mapping, Sequence, Sized
from typing import Any, TypeVar, overload

from markupsafe import Markup

T = TypeVar("T")
D = TypeVar("D")
K = TypeVar("K")
V = TypeVar("V")


def upper(value: str) -> str: ...
def lower(value: str) -> str: ...
def title(value: str) -> str: ...
def capitalize(value: str) -> str: ...
def trim(value: str, chars: str | None = None) -> str: ...
def striptags(value: object) -> str: ...
def replace(value: str, old: str, new: str, count: int | None = None) -> str: ...
def length(value: Sized) -> int: ...
def count(value: Sized) -> int: ...
def join(
    value: Iterable[object], d: str = "", attribute: str | int | None = None
) -> str: ...
def safe(value: str) -> Markup: ...
def escape(value: object) -> Markup: ...
def e(value: object) -> Markup: ...
def string(value: object) -> str: ...
def int_(value: object, default: int = 0, base: int = 10) -> int: ...
def float_(value: object, default: float = 0.0) -> float: ...
def abs_(value: float) -> float: ...
def round_(value: float, precision: int = 0, method: str = "common") -> float: ...
def sum_(
    value: Iterable[float], attribute: str | None = None, start: float = 0
) -> float: ...
def list_(value: Iterable[T]) -> list[T]: ...
def first(value: Sequence[T]) -> T: ...
def last(value: Sequence[T]) -> T: ...
def sort(
    value: Iterable[T],
    reverse: bool = False,
    case_sensitive: bool = False,
    attribute: str | int | None = None,
) -> list[T]: ...
def reverse(value: Sequence[T]) -> Sequence[T]: ...
def format(value: str, *args: object, **kwargs: object) -> str: ...
def tojson(value: object, indent: int | None = None) -> Markup: ...
def xmlattr(value: Mapping[str, object], autospace: bool = True) -> Markup: ...
def urlencode(value: str | Mapping[str, object] | Iterable[Any]) -> str: ...
def truncate(
    value: str,
    length: int = 255,
    killwords: bool = False,
    end: str = "...",
    leeway: int | None = None,
) -> str: ...
def forceescape(value: object) -> Markup: ...
def wordcount(value: str) -> int: ...
def center(value: str, width: int = 80) -> str: ...
def indent(
    value: str, width: int | str = 4, first: bool = False, blank: bool = False
) -> str: ...
def filesizeformat(value: float, binary: bool = False) -> str: ...
def pprint(value: object) -> str: ...
def attr(value: object, name: str) -> Any: ...
def items(value: Mapping[K, V]) -> Iterator[tuple[K, V]]: ...
def min_(
    value: Iterable[T], case_sensitive: bool = False, attribute: str | int | None = None
) -> T: ...
def max_(
    value: Iterable[T], case_sensitive: bool = False, attribute: str | int | None = None
) -> T: ...
def unique(
    value: Iterable[T], case_sensitive: bool = False, attribute: str | int | None = None
) -> Iterator[T]: ...
def select(
    value: Iterable[T], test: str | None = None, *args: Any, **kwargs: Any
) -> Iterator[T]: ...
def reject(
    value: Iterable[T], test: str | None = None, *args: Any, **kwargs: Any
) -> Iterator[T]: ...
def selectattr(
    value: Iterable[T], attr: str, test: str | None = None, *args: Any, **kwargs: Any
) -> Iterator[T]: ...
def rejectattr(
    value: Iterable[T], attr: str, test: str | None = None, *args: Any, **kwargs: Any
) -> Iterator[T]: ...
def map_(value: Iterable[Any], *args: Any, **kwargs: Any) -> Iterator[Any]: ...
def groupby(
    value: Iterable[T],
    attribute: str | int,
    default: object = None,
    case_sensitive: bool = False,
) -> list[tuple[Any, list[T]]]: ...
def dictsort(
    value: Mapping[K, V],
    case_sensitive: bool = False,
    by: str = "key",
    reverse: bool = False,
) -> list[tuple[K, V]]: ...
def slice_(
    value: Iterable[T], slices: int, fill_with: object = None
) -> Iterator[list[T]]: ...
def batch(
    value: Iterable[T], linecount: int, fill_with: object = None
) -> Iterator[list[T]]: ...


@overload
def default(value: T | None, default_value: D, boolean: bool = False) -> T | D: ...
@overload
def default(value: T | None, *, boolean: bool = False) -> T | str: ...
def default(value: Any, default_value: Any = "", boolean: bool = False) -> Any: ...


d = default
