"""Typed access to the benchmark templates.

``typed_templates.pyi`` is generated by ``make check-templates``.
It overloads ``get_template`` per template name,
so that ``render()`` is checked against the template's declared context.
"""

from jinja2 import Environment, Template


def get_template(env: Environment, name: str) -> Template:
    return env.get_template(name)
