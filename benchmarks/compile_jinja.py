"""Emit Jinja's generated Python for the benchmark template for inspection."""

from pathlib import Path

from jinja2 import Environment, select_autoescape


def main() -> None:
    template_path = Path(__file__).with_name("templates") / "articles.jinja2"
    template_source = template_path.read_text(encoding="utf-8")
    environment = Environment(autoescape=select_autoescape(default=True))
    generated = environment.compile(
        template_source,
        name="benchmark_template",
        filename=str(template_path),
        raw=True,
    )
    output = Path(__file__).with_name("generated_jinja.py")
    output.write_text(
        "# Generated by `python -m benchmarks.compile_jinja`; do not edit.\n" + generated,
        encoding="utf-8",
    )
    print(f"Wrote generated Jinja Python to {output}")


if __name__ == "__main__":
    main()
